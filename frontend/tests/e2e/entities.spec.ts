import { expect, test } from '@playwright/test'

test('admin manages an entity, views history, deactivates and restores it', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /enter shared workspace/i }).click()
  await page.getByRole('button', { name: 'Operations', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Supply-chain entities' })).toBeVisible()
  await page.getByRole('button', { name: 'Warehouses', exact: true }).click()
  await page.getByRole('button', { name: 'Create entity', exact: true }).click()
  const stamp = Date.now()
  await page.getByLabel('Warehouse code', { exact: true }).fill(`QA-${stamp}`)
  await page.getByLabel('Warehouse name', { exact: true }).fill(`QA warehouse ${stamp}`)
  await page.getByLabel('Location', { exact: true }).fill('Controlled test site')
  await page.getByLabel('Reason for change').fill('QA warehouse onboarding')
  await page.getByRole('button', { name: 'Save entity', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Entity saved')
  await page.getByRole('button', { name: 'Edit entity', exact: true }).click()
  await page.getByLabel('Warehouse name', { exact: true }).fill(`Edited warehouse ${stamp}`)
  await page.getByLabel('Reason for change').fill('QA name correction')
  await page.getByRole('button', { name: 'Save entity', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Edited warehouse ${stamp}`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Deactivate entity', exact: true }).click()
  await page.getByLabel('Reason', { exact: true }).fill('QA warehouse retired')
  await page.getByRole('button', { name: 'Confirm deactivation', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Entity deactivated')
  await page.getByRole('button', { name: 'Restore entity', exact: true }).click()
  await page.getByLabel('Reason', { exact: true }).fill('QA warehouse restored')
  await page.getByRole('button', { name: 'Confirm restore', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Entity restored')
  await expect(page.getByRole('heading', { name: 'Audit history (administrator / auditor)' })).toBeVisible()
  await page.getByLabel('Search', { exact: true }).fill(`Edited warehouse ${stamp}`)
  await expect(page.locator('.entity-table tbody tr')).toHaveCount(1)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true })
})
